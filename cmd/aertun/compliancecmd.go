// NIST compliance evidence, from the signed chain rather than from a
// spreadsheet (internal/compliance).
//
// Three things live here. `controls` prints the map — which SP 800-53
// controls this program's detections and features are entries under, read
// from the same mapping.json the binary reasons from. `evidence` builds the
// pack for one control: the matching audit records, each with its RFC 6962
// inclusion proof into a tree head signed twice (Ed25519 and ML-DSA-65), and
// the offline steps a third party performs. `verify` is those steps: a saved
// pack and the published public keys, and nothing from this store that the
// pack could have vouched for itself with.
//
// The line this surface holds is the one auditlog holds: the pack is the log
// opened to a third party — pseudonymised, but whole for its control — so it
// is generated by a person at a terminal and never offered to an agent.

func complianceUsage() error {
	return fmt.Errorf("usage: aertun compliance controls | evidence CONTROL " +
		"[--out FILE] | verify FILE [--keys KEYS]")
}

// cmdCompliance is the compliance command surface.
func cmdCompliance(root string, args []string) error {
	if len(args) == 0 {
		return complianceUsage()
	}
	switch args[0] {
	case "controls":
		return complianceControls()
	case "evidence":
		return complianceEvidence(root, args[1:])
	case "verify":
		return complianceVerify(root, args[1:])
	}
	return complianceUsage()
}

// complianceControls lists the map: every control the mapping names, with
// the entries under it.
//
// The readable form is one line per control, ids only — the thing somebody
// running this wants to answer is "is my control covered", and the entry
// titles are one `evidence` call away. The control ids are sorted, so the
// output is diffable between versions of the mapping.
func complianceControls() error {
	m, err := compliance.Load()
	if err != nil {
		return err
	}
	controls := m.Controls()

	type row struct {
		Control string                 `json:"control"`
		Entries []compliance.PackEntry `json:"entries"`
	}
	rows := make([]row, 0, len(controls))
	for _, c := range controls {
		r := row{Control: c}
		for _, e := range m.EntriesFor(c) {
			r.Entries = append(r.Entries, compliance.PackEntry{
				ID: e.ID, Kind: e.Kind, Title: e.Title,
				Actions: e.Evidence.Actions, Proves: e.Evidence.Proves,
			})
		}
		rows = append(rows, r)
	}

	if w.JSON(map[string]any{
		"controls": rows,
		"catalogs": m.Catalogs,
		"entries":  len(m.Entries),
	}) {
		return nil
	}
	w.Human("%s%d controls%s, %d mapped entries, SP 800-53 %s\n",
		bold, len(controls), reset, len(m.Entries),
		m.Catalogs["nist-sp-800-53"])
	for _, r := range rows {
		ids := make([]string, 0, len(r.Entries))
		for _, e := range r.Entries {
			ids = append(ids, e.ID)
		}
		w.Human("  %-10s %s\n", r.Control, strings.Join(ids, ", "))
	}
	w.Human("\n  %sevidence for one: aertun compliance evidence AC-2 "+
		"--out ac2.json%s\n", dim, reset)
	return nil
}

// complianceEvidence builds the pack for one control from the signed log.
//
// It reads the whole log and signs a head over it, the same way
// `aertun auditlog head` does; the head is what makes the pack's proofs
// third-party checkable rather than self-consistent. Nothing is written back
// to the log before the head is taken, so the pack describes the log exactly
// as the head commits to it; the act of generating one is recorded after,
// which leaves the pack one entry behind the live log and honest about the
// moment it was taken.
func complianceEvidence(root string, args []string) error {
	pos, flags := leadingArgs(args, 1)
	fs := flag.NewFlagSet("evidence", flag.ContinueOnError)
	outPath := fs.String("out", "",
		"write the pack here rather than stdout")
	if err := fs.Parse(flags); err != nil {
		return err
	}
	if len(pos) != 1 || strings.TrimSpace(pos[0]) == "" {
		return fmt.Errorf(
			"usage: aertun compliance evidence CONTROL [--out FILE]")
	}
	control := pos[0]

	m, err := compliance.Load()
	if err != nil {
		return err
	}
	events, err := audit.Read(auditPath(root))
	if err != nil {
		return err
	}
	signer, err := headSigner(root)
	if err != nil {
		return err
	}
	pack, err := compliance.EvidencePack(m, control, events, signer,
		time.Now().UTC())
	if err != nil {
		// An unmapped control is a question about coverage, and the answer
		// is the map rather than a bare refusal.
		if errors.Is(err, compliance.ErrUnmappedControl) {
			return fmt.Errorf("%v\n  aertun compliance controls lists what "+
				"the mapping covers", err)
		}
		return err
	}

	// CA-2: the assessment act itself leaves a trail. Recorded after the
	// head was signed, so the pack is a snapshot and this entry says who
	// took one and when — the question a reviewer asks of any evidence
	// gathering, answered in the same chain the evidence came from.
	record(root, resolveCaller(root, flagToken).auditRecord(
		"compliance.evidence", "/", audit.Success, map[string]string{
			"control": control, "records": fmt.Sprint(len(pack.Records)),
			"head": fmt.Sprint(pack.Head.Size),
		}))

	body, err := json.MarshalIndent(pack, "", "  ")
	if err != nil {
		return err
	}
	if *outPath == "" {
		// The document is the artefact, so it goes to stdout whole in
		// either mode: a --json caller parses the same bytes a person reads.
		// Through w.Out rather than fmt.Println so the process has one
		// stdout, which is what a pipe in a script — and a capture in a
		// test — is holding.
		fmt.Fprintln(w.Out, string(body))
		return nil
	}
	if err := os.WriteFile(*outPath, append(body, '\n'), 0o600); err != nil {
		return err
	}
	if w.JSON(map[string]any{"written": *outPath, "control": control,
		"records": len(pack.Records), "head": pack.Head}) {
		return nil
	}
	w.Human("%s%s%s — %d record(s) from a log of %d entries, head signed "+
		"by %s\n", bold, *outPath, reset, len(pack.Records), pack.Head.Size,
		pack.Head.KeyID)
	if len(pack.Records) == 0 {
		for _, s := range pack.Satisfies {
			w.Human("  %s%s%s\n", dim, s, reset)
		}
	}
	w.Human("\n  %sa third party checks it offline: aertun compliance "+
		"verify %s --keys %s%s\n", dim, *outPath, headKeysPath(root), reset)
	return nil
}

// complianceVerify is the third-party path: a saved pack, the published
// public keys, and nothing else from this store.
//
// The keys default to this store's published file because that is what the
// person generating a pack has, and --keys exists because that is not who
// this subcommand is for: an auditor checks a pack against the keys they
// were given, and reading the keys from the machine that made the pack would
// be checking a claim against itself.
func complianceVerify(root string, args []string) error {
	pos, flags := leadingArgs(args, 1)
	fs := flag.NewFlagSet("verify", flag.ContinueOnError)
	keysPath := fs.String("keys", "",
		"published public keys for the head (default: this store's)")
	if err := fs.Parse(flags); err != nil {
		return err
	}
	if len(pos) != 1 {
		return fmt.Errorf(
			"usage: aertun compliance verify FILE [--keys KEYS]")
	}
	from := headKeysPath(root)
	if *keysPath != "" {
		from = *keysPath
	}

	body, err := os.ReadFile(pos[0])
	if err != nil {
		return err
	}
	kb, err := os.ReadFile(from)
	if err != nil {
		return fmt.Errorf("cannot read the public keys at %s: %w", from, err)
	}
	var pub publishedKeys
	if err := json.Unmarshal(kb, &pub); err != nil {
		return fmt.Errorf("%s is not a published key file: %w", from, err)
	}
	ed, err := base64.StdEncoding.DecodeString(pub.Ed25519)
	if err != nil {
		return fmt.Errorf("the published Ed25519 key is not base64: %w", err)
	}
	ml, err := base64.StdEncoding.DecodeString(pub.MLDSA)
	if err != nil {
		return fmt.Errorf("the published ML-DSA key is not base64: %w", err)
	}
	v, err := audit.NewHeadVerifier(ed, ml)
	if err != nil {
		return err
	}

	pack, err := compliance.VerifyPack(body, v)
	if err != nil {
		return err
	}
	if w.JSON(map[string]any{
		"verified": true, "control": pack.Control,
		"records": len(pack.Records), "head": pack.Head,
		"steps": compliance.VerifySteps(),
	}) {
		return nil
	}
	w.Human("%sverified%s  control %s, %d record(s)\n", bold, reset,
		pack.Control, len(pack.Records))
	w.Human("  %shead of %d entries, root %s, key %s, both signatures "+
		"check out%s\n", dim, pack.Head.Size, pack.Head.Root,
		pack.Head.KeyID, reset)
	w.Human("\n  %swhat was checked, offline and without the log:%s\n",
		dim, reset)
	for _, s := range compliance.VerifySteps() {
		w.Human("  %s- %s%s\n", dim, s, reset)
	}
	return nil
}
