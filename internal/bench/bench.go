// Package bench is aertunbench v0: the open benchmark of agentic-SOC
// accuracy, beginning with the number no vendor publishes — how often the
// analyst would have closed a real attack (docs/research white space 11).
//
// # What v0 honestly is
//
// A harness and a corpus that measure THIS analyst, on THIS corpus, with the
// model named in the results document. It is not a cross-vendor ranking:
// anybody may run it against their own analyst, and the document says what
// ran. The corpus is labelled data shipped with the program, versioned by
// schema, generated by code in this package (generate.go) so every label and
// its provenance can be reviewed as a diff rather than as a data dump.
//
// # What a case is
//
// One case is a finding's gathered analyst.State — the exact shape
// internal/analyst hands a model, counted facts and untrusted text apart —
// plus the class a person ruled it (real / false-positive / benign) and
// where that label came from:
//
//   - derived-from-dispositions: the label follows the recorded rulings on
//     sibling findings that the case's own facts carry, standing in for an
//     organisation's own `analyst eval` export;
//   - hand-labeled-from-catalogue: the label was set by hand for a scenario
//     the record does not decide — benign twins, count-shaped sprays, thin
//     first sightings — which are exactly the cases a record-led analyst
//     gets wrong.
//
// # What is measured
//
// The metrics follow the eval methodology (docs/research/07 §5.2): FNR on
// real with a Wilson interval is primary, because the cost asymmetry is the
// whole argument for measuring false closures at all. Precision, recall and
// F1 treat real as the positive class over pooled runs, with abstentions
// counted apart rather than as errors: an analyst that says "a person
// decides this one" has done the safe thing. Each case runs k times and
// counts only when every run was right (pass^k). The injection suite
// (inject.go) replants every attacker-writable field with instructions in
// the shapes that turn up in logs, and the hijack rate reports how often
// that moved a verdict — internal/analyst's Hijacked measure, generalised
// over more payload families.
//
// # What the document proves
//
// A results document carries a sha256 self-digest, so a rendered number can
// be checked against the file it came from. That is a check against
// sloppiness, not against forgery: nothing here is signed, and the honest
// claim is that dual-signing arrives with the content plane
// (internal/detect's signed packs), which will sign these documents the
// same way it signs rules.
package bench

import (
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"

	"github.com/aertun/aertun/internal/analyst"
)

// Schema is the corpus version this build reads. A corpus whose schema is
// not this is a corpus from another release, and refusing it is better than
// measuring cases against metrics that have since changed meaning.
const Schema = 1

// The two places a label can have come from. A closed set, because
// "provenance: various" is a field nobody can audit.
const (
	FromDispositions = "derived-from-dispositions"
	HandLabelled     = "hand-labeled-from-catalogue"
)

//go:embed corpus.json
var corpusFS embed.FS

// Corpus is the labelled benchmark set.
type Corpus struct {
	Schema int `json:"schema"`
	// Name is what a results document names as the benchmark it ran.
	Name string `json:"name"`
	// Cases are the labelled gathered states, in a fixed order so two runs
	// over the same corpus produce comparable documents.
	Cases []Case `json:"cases"`
}

// Case is one finding as the analyst would have been shown it, with the
// class a person ruled it and where that label came from.
type Case struct {
	Name string `json:"name"`
	// Expect is the ruled class: one of the three closed verdict words.
	Expect string `json:"expect"`
	// Provenance says where the label came from. Derived labels follow the
	// dispositions the case itself records; hand labels are the cases the
	// record does not decide, and are the ones to re-read first.
	Provenance string `json:"provenance"`
	// Inject marks the cases the injection suite replants. A subset,
	// because hijack attempts are expensive against a real model and the
	// subset is chosen to cover every class.
	Inject bool `json:"inject,omitempty"`
	// State is the gathered analyst.State: counted facts and untrusted
	// text, the exact shape the triage plan produces.
	State analyst.State `json:"state"`
}

// Load reads the corpus that ships with the program.
func Load() (*Corpus, error) {
	b, err := corpusFS.ReadFile("corpus.json")
	if err != nil {
		return nil, err
	}
	var c Corpus
	dec := json.NewDecoder(strings.NewReader(string(b)))
	// A field the schema does not know is a corpus from another schema
	// wearing this one's number, and silently ignoring it would measure
	// something other than what the file says.
	dec.DisallowUnknownFields()
	if err := dec.Decode(&c); err != nil {
		return nil, fmt.Errorf("corpus.json: %w", err)
	}
	if err := c.Validate(); err != nil {
		return nil, err
	}
	return &c, nil
}

// CorpusDigest is the sha256 of the corpus bytes the program carries, so a
// results document can name the exact corpus it ran — the same honesty as
// naming the model: a number is not comparable without both.
func CorpusDigest() string {
	b, err := corpusFS.ReadFile("corpus.json")
	if err != nil {
		return ""
	}
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// Counts summarises the corpus by class and by label provenance, for the
// head of a results document: what was measured, said before how well it
// went.
type Counts struct {
	Cases   int `json:"cases"`
	Real    int `json:"real"`
	False   int `json:"false_positive"`
	Benign  int `json:"benign"`
	Inject  int `json:"injection_cases"`
	Derived int `json:"derived_from_dispositions"`
	Hand    int `json:"hand_labeled"`
}

// Summary counts the corpus.
func (c *Corpus) Summary() Counts {
	var s Counts
	s.Cases = len(c.Cases)
	for _, cs := range c.Cases {
		switch cs.Expect {
		case analyst.Real:
			s.Real++
		case analyst.FalsePositive:
			s.False++
		case analyst.Benign:
			s.Benign++
		}
		if cs.Inject {
			s.Inject++
		}
		if cs.Provenance == FromDispositions {
			s.Derived++
		} else {
			s.Hand++
		}
	}
	return s
}

var reCaseName = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,63}$`)

// Validate refuses a corpus that could not be measured honestly.
//
// The shape checks are the ones the pipeline itself guarantees: untrusted
// text arrives tamed, so a corpus case carrying a fence marker or a newline
// in its title, entity or evidence is a case the real analyst never sees —
// and measuring the model on states it will never be handed is a benchmark
// of nothing.
func (c *Corpus) Validate() error {
	if c.Schema != Schema {
		return fmt.Errorf("corpus schema is %d; this build reads %d",
			c.Schema, Schema)
	}
	if strings.TrimSpace(c.Name) == "" {
		return fmt.Errorf("the corpus has no name")
	}
	if len(c.Cases) == 0 {
		return fmt.Errorf("the corpus holds no cases")
	}
	seen := map[string]bool{}
	for _, cs := range c.Cases {
		if !reCaseName.MatchString(cs.Name) {
			return fmt.Errorf("%q is not a usable case name", cs.Name)
		}
		if seen[cs.Name] {
			return fmt.Errorf("%q appears twice; a case is one finding", cs.Name)
		}
		seen[cs.Name] = true
		if cs.Expect != analyst.Real && cs.Expect != analyst.FalsePositive &&
			cs.Expect != analyst.Benign {
			return fmt.Errorf("%s expects %q, which is not a verdict", cs.Name,
				cs.Expect)
		}
		if cs.Provenance != FromDispositions && cs.Provenance != HandLabelled {
			return fmt.Errorf("%s labels come from %q, which is not a "+
				"provenance", cs.Name, cs.Provenance)
		}
		if err := tamedShape(cs.Name, cs.State); err != nil {
			return err
		}
	}
	return nil
}

// tamedShape checks the untrusted half of a case is the shape Gather
// produces: one bounded line per field, nothing that draws a fence.
func tamedShape(name string, st analyst.State) error {
	fields := append([]string{st.Untrusted.Title, st.Untrusted.Entity},
		st.Untrusted.Evidence...)
	for n, text := range fields {
		for _, mark := range []string{"<<<", ">>>", "```", "\n"} {
			if strings.Contains(text, mark) {
				return fmt.Errorf("%s's untrusted text carries %q, which the "+
					"plan tames away before a model is shown it", name, mark)
			}
		}
		if len(text) > maxEvidenceText+4 && n > 1 {
			return fmt.Errorf("%s's evidence line %d is %d bytes, over the "+
				"gather bound", name, n-1, len(text))
		}
	}
	if len(st.Untrusted.Evidence) > maxEvidence {
		return fmt.Errorf("%s carries %d evidence lines, over the gather "+
			"bound of %d", name, len(st.Untrusted.Evidence), maxEvidence)
	}
	return nil
}
